#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const sdkPackagePath = path.join(root, "packages/sdk/package.json");
const codegenPackagePath = path.join(
  root,
  "packages/workspace-codegen/package.json",
);
const outputPath = path.join(
  root,
  "packages/sdk/src/authoring/generated-metadata.ts",
);
const check = process.argv.includes("--check");

async function readJson(filePath) {
  return JSON.parse(await readFile(filePath, "utf8"));
}

const [sdkPackageJson, codegenPackageJson] = await Promise.all([
  readJson(sdkPackagePath),
  readJson(codegenPackagePath),
]);

const source = `// Generated by scripts/generate-authoring-metadata.mjs. Do not edit by hand.
import type { GeneratedAuthoringMetadataV1 } from "./types.js";

export const GENERATED_AUTHORING_METADATA = {
  sdkVersion: ${JSON.stringify(sdkPackageJson.version)},
  codegenVersion: ${JSON.stringify(codegenPackageJson.version)},
  manifestSchemaVersion: 2,
  generatedArtifactSchemaVersion: 1,
} as const satisfies GeneratedAuthoringMetadataV1;
`;

if (check) {
  const current = await readFile(outputPath, "utf8").catch(() => null);
  if (current !== source) {
    throw new Error(
      `${path.relative(root, outputPath)} is stale. Run pnpm authoring-metadata:generate.`,
    );
  }
} else {
  await writeFile(outputPath, source);
}
