#!/usr/bin/env node
import { pathToFileURL } from "node:url";
import prettier from "prettier";
import {
  catalogOutputPath,
  collectValidatedScenarioCatalog,
  repoRelative,
  toPublicScenarioEntry,
  writeGeneratedText,
} from "./scenario-catalog-lib.mjs";
import { generateComponentScenarioIndex } from "./generate-component-scenario-index.mjs";

async function renderCatalogSource(entries) {
  const publicEntries = entries.map(toPublicScenarioEntry);
  const renderedEntries = publicEntries
    .map((entry) => {
      const moduleImportPath = `../../../fixtures/ui/reference-games/${entries.find((candidate) => candidate.id === entry.id)?.renderModule}`;
      return `{
  id: ${JSON.stringify(entry.id)},
  title: ${JSON.stringify(entry.title)},
  gameId: ${JSON.stringify(entry.gameId)},
  fixtureUrl: ${JSON.stringify(entry.fixtureUrl)},
  renderModuleUrl: ${JSON.stringify(entry.renderModuleUrl)},
  renderModuleLoader: () => import(${JSON.stringify(moduleImportPath)}),
  components: ${JSON.stringify(entry.components)},
  capabilities: ${JSON.stringify(entry.capabilities)},
  viewportTags: ${JSON.stringify(entry.viewportTags)},
  sourceDigest: ${JSON.stringify(entry.sourceDigest)},
}`;
    })
    .join(",\n");
  return prettier.format(
    `// Generated by scripts/ui/generate-scenario-catalog.mjs. Do not edit by hand.
import type { UIScenarioRenderModule } from "./runtime/browser-fixture-runtime.js";

export interface UIScenarioCatalogEntry {
  readonly id: string;
  readonly title: string;
  readonly gameId: string;
  readonly fixtureUrl: string;
  readonly renderModuleUrl: string;
  readonly renderModuleLoader?: () => Promise<UIScenarioRenderModule>;
  readonly components: readonly string[];
  readonly capabilities: readonly string[];
  readonly viewportTags: readonly string[];
  readonly sourceDigest: string;
}

export function defineUIScenarios(
  entries: readonly UIScenarioCatalogEntry[],
): readonly UIScenarioCatalogEntry[] {
  const seen = new Set<string>();
  return entries.map((entry) => {
    if (seen.has(entry.id)) {
      throw new Error(\`Duplicate UI Workbench scenario '\${entry.id}'.\`);
    }
    seen.add(entry.id);
    return Object.freeze({ ...entry });
  });
}

export const scenarios = defineUIScenarios([${renderedEntries}] satisfies readonly UIScenarioCatalogEntry[]);
`,
    { parser: "typescript" },
  );
}

export async function generateScenarioCatalog({ check = false } = {}) {
  const entries = await collectValidatedScenarioCatalog();
  const wroteIndex = await generateComponentScenarioIndex({ check, entries });
  const wroteCatalog = await writeGeneratedText(
    catalogOutputPath,
    await renderCatalogSource(entries),
    { check },
  );
  return {
    scenarios: entries.length,
    wroteCatalog,
    wroteIndex,
  };
}

async function main() {
  const check = process.argv.includes("--check");
  const result = await generateScenarioCatalog({ check });
  const mode = check ? "checked" : "generated";
  console.log(
    `${mode} ${result.scenarios} UI scenarios at ${repoRelative(
      catalogOutputPath,
    )}`,
  );
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
