#!/usr/bin/env node
import path from "node:path";
import { pathToFileURL } from "node:url";
import prettier from "prettier";
import {
  collectValidatedScenarioCatalog,
  generatedWorkbenchRoot,
  repoRelative,
  toPublicScenarioEntry,
  writeGeneratedText,
} from "./scenario-catalog-lib.mjs";
import { generateComponentScenarioIndex } from "./generate-component-scenario-index.mjs";

async function renderCatalogSource(
  entries,
  { catalogPath, fixtureBundleRoot },
) {
  const publicEntries = entries.map(toPublicScenarioEntry);
  const renderedEntries = publicEntries
    .map((entry) => {
      const renderModule = entries.find(
        (candidate) => candidate.id === entry.id,
      )?.renderModule;
      if (!renderModule) {
        throw new Error(`${entry.id} is missing a render module.`);
      }
      const moduleImportPath = path
        .relative(
          path.dirname(catalogPath),
          path.join(fixtureBundleRoot, renderModule),
        )
        .split(path.sep)
        .join("/");
      const moduleSpecifier = moduleImportPath.startsWith(".")
        ? moduleImportPath
        : `./${moduleImportPath}`;
      return `{
  id: ${JSON.stringify(entry.id)},
  title: ${JSON.stringify(entry.title)},
  gameId: ${JSON.stringify(entry.gameId)},
  fixtureUrl: ${JSON.stringify(entry.fixtureUrl)},
  renderModuleUrl: ${JSON.stringify(entry.renderModuleUrl)},
  renderModuleLoader: () => import(${JSON.stringify(moduleSpecifier)}),
  components: ${JSON.stringify(entry.components)},
  capabilities: ${JSON.stringify(entry.capabilities)},
  viewportTags: ${JSON.stringify(entry.viewportTags)},
  sourceDigest: ${JSON.stringify(entry.sourceDigest)},
}`;
    })
    .join(",\n");
  return prettier.format(
    `// Generated by scripts/ui/generate-scenario-catalog.mjs. Do not edit by hand.
function defineUIScenarios(entries) {
  const seen = new Set<string>();
  return entries.map((entry) => {
    if (seen.has(entry.id)) {
      throw new Error(\`Duplicate UI Workbench scenario '\${entry.id}'.\`);
    }
    seen.add(entry.id);
    return Object.freeze({ ...entry });
  });
}

export const scenarios = defineUIScenarios([${renderedEntries}]);
`,
    { parser: "typescript" },
  );
}

export async function generateScenarioCatalog({
  check = false,
  generatedRoot = generatedWorkbenchRoot,
  checkComponentIndex = true,
} = {}) {
  const resolvedGeneratedRoot = path.resolve(generatedRoot);
  const fixtureBundleRoot = path.join(
    resolvedGeneratedRoot,
    "fixtures/reference-games",
  );
  const generatedCatalogPath = path.join(resolvedGeneratedRoot, "catalog.ts");
  const entries = await collectValidatedScenarioCatalog({ fixtureBundleRoot });
  const wroteIndex = checkComponentIndex
    ? await generateComponentScenarioIndex({ check, entries })
    : false;
  const wroteCatalog = await writeGeneratedText(
    generatedCatalogPath,
    await renderCatalogSource(entries, {
      catalogPath: generatedCatalogPath,
      fixtureBundleRoot,
    }),
    { check },
  );
  return {
    scenarios: entries.length,
    wroteCatalog,
    wroteIndex,
    catalogPath: generatedCatalogPath,
    fixtureBundleRoot,
  };
}

async function main() {
  const check = process.argv.includes("--check");
  const outIndex = process.argv.indexOf("--out");
  const generatedRoot =
    outIndex >= 0 ? process.argv[outIndex + 1] : generatedWorkbenchRoot;
  const result = await generateScenarioCatalog({
    check,
    generatedRoot,
    checkComponentIndex: !process.argv.includes("--skip-component-index"),
  });
  const mode = check ? "checked" : "generated";
  console.log(
    `${mode} ${result.scenarios} UI scenarios at ${repoRelative(
      result.catalogPath,
    )}`,
  );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
