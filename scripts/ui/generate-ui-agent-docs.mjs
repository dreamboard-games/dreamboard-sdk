#!/usr/bin/env node
import { readFile } from "node:fs/promises";
import path from "node:path";
import prettier from "prettier";
import {
  collectValidatedScenarioCatalog,
  componentScenarioIndexPath,
  repoRelative,
  root,
  writeGeneratedText,
} from "./scenario-catalog-lib.mjs";
import {
  expectedReferenceGames,
  referenceGamesRoot,
  readJson,
} from "./reference-games-lib.mjs";
import {
  requiredReferenceGameIds,
  requiredWorkbenchScenarioIds,
} from "./required-ui-scenarios.mjs";

const uiAgentDocPath = path.join(root, "docs/ui-agent-iteration.md");
const referenceGamesDocPath = path.join(root, "docs/reference-games.md");
const requiredScenarioIds = new Set(requiredWorkbenchScenarioIds);
const requiredGameIds = new Set(requiredReferenceGameIds);

function table(headers, rows) {
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
}

function formatList(values) {
  return values.length > 0 ? values.join(", ") : "none";
}

function componentContractRows(componentIndex) {
  return Object.values(componentIndex.contracts ?? {})
    .filter((entry) => entry.kind === "component")
    .sort((left, right) => left.id.localeCompare(right.id))
    .map((entry) => [
      entry.id,
      formatList((entry.scenarioIds ?? []).map((id) => `\`${id}\``)),
      formatList(
        (entry.capabilities ?? []).map((capability) => `\`${capability}\``),
      ),
    ]);
}

async function renderUiAgentIterationDoc({ scenarios, componentIndex }) {
  const packageJson = await readJson(path.join(root, "package.json"));
  const decisionRows = [
    [
      "Pure color or spacing token",
      "`pnpm ui:test:changed --base origin/main`",
    ],
    ["`HandView` behavior", "`pnpm ui:test --component HandView`"],
    ["Pointer/drag adapter", "`pnpm ui:test --capability pointer-drag`"],
    [
      "Runtime draft",
      "`pnpm ui:test --capability runtime-draft && pnpm ui:test:packed`",
    ],
    [
      "Runtime submit",
      "`pnpm ui:test --capability runtime-submit && pnpm ui:test:packed`",
    ],
    [
      "Composed runtime visuals",
      "`pnpm ui:test:runtime-visual` (`pnpm ui:test:runtime-visual:update` to accept intentional changes)",
    ],
    [
      "Browser-interaction protocol",
      "Full `pnpm ui:check`, Hearts packed proof, and Hearts real-host parity",
    ],
  ];
  const componentRows = componentContractRows(componentIndex);
  const scenarioRows = scenarios.map((scenario) => [
    `\`${scenario.id}\``,
    requiredScenarioIds.has(scenario.id)
      ? "Required foundation"
      : "Optional follow-up",
    scenario.title,
    formatList(scenario.components.map((component) => `\`${component}\``)),
    formatList(scenario.capabilities.map((capability) => `\`${capability}\``)),
  ]);

  return prettier.format(
    `# UI Agent Iteration

<!-- Generated by scripts/ui/generate-ui-agent-docs.mjs. Do not edit by hand. -->

This guide is generated from the live UI scenario catalog and root command map.

## Command Tiers

- PR fast gate: \`${packageJson.scripts["ui:test:changed"]}\`
- Main full gate: \`${packageJson.scripts["ui:check"]}\`
- Runtime visual gate: \`${packageJson.scripts["ui:test:runtime-visual"]}\`
- Release proof: \`${packageJson.scripts["ui:release-proof"]}\`
- Focused Workbench route: \`pnpm ui:workbench -- --scenario <scenario-id>\`

## Scenario Selection

Use \`fixtures/ui/component-scenario-index.json\` to map changed component files
to scenario IDs. Shared runtime, theme, fixture, or browser-interaction changes
fall back to the required Workbench scenario set: Hearts mobile interaction,
desktop card drag, and desktop runtime draft. Other checked-in scenarios remain
available for focused follow-up coverage but do not block the foundation release.

${table(["Change", "Minimum command"], decisionRows)}

## Components

${table(["Component", "Workbench scenarios", "Capabilities"], componentRows)}

## Scenarios

${table(["Scenario", "Release role", "Title", "Components", "Capabilities"], scenarioRows)}

## Evidence

Workbench receipts record semantic, projection, draft, and submission digests
under \`artifacts/ui/<run-id>/receipt.json\`. Storybook interaction and visual
receipts are written under \`artifacts/ui-stories\` and \`artifacts/ui-visual\`.
Workbench runtime visual baselines live beside
\`packages/ui-workbench/tests/runtime-visual.spec.ts\` and are updated only by
\`pnpm ui:test:runtime-visual:update\`.
Packed verification writes \`build/reference-games/packed-consumer-receipt.json\`,
and release proof writes \`artifacts/ui-release-proof/<run-id>/receipt.json\`.
Attach the relevant receipt paths and any parity receipt to handoff notes.
`,
    { parser: "markdown" },
  );
}

async function renderReferenceGamesDoc({ scenarios }) {
  const rows = [];
  for (const game of expectedReferenceGames) {
    const manifest = await readJson(
      path.join(referenceGamesRoot, game.id, "reference-game.json"),
    );
    rows.push([
      `\`${game.id}\``,
      requiredGameIds.has(game.id)
        ? "Required foundation"
        : "Optional follow-up",
      game.displayName,
      formatList(manifest.mechanics.map((mechanic) => `\`${mechanic}\``)),
      formatList(manifest.uiPatterns.map((pattern) => `\`${pattern}\``)),
      scenarios
        .filter((scenario) => scenario.gameId === game.id)
        .map((scenario) => `\`${scenario.id}\``)
        .join(", "),
    ]);
  }

  return prettier.format(
    `# Reference Games

<!-- Generated by scripts/ui/generate-ui-agent-docs.mjs. Do not edit by hand. -->

Reference games are SDK-owned packed consumers. They use exact SDK dependency
versions, remain out of public demo galleries, and provide the fixture bundle
consumed by the UI Workbench and parity proof.

${table(["Game", "Release role", "Display name", "Mechanics", "UI patterns", "Scenarios"], rows)}

## Packed Verification

Run \`pnpm reference-games:check\` for source validation and
\`pnpm reference-games:test:packed --required\` for the required isolated
packed-consumer proof. The packed proof covers the Hearts, Hex Network Trading,
and Worker Placement Tableau consumers and must install the SDK tarball rather
than workspace source links. Other reference consumers are optional follow-up
coverage.

## Fixture Bundle

Run \`pnpm reference-games:bundle\` to produce
\`build/reference-games/reference-bundle.lock.json\`,
\`build/reference-games/reference-games-bundle.tgz\`, and the exact SDK tarball
used by parity and release proof.
`,
    { parser: "markdown" },
  );
}

export async function generateUiAgentDocs({ check = false } = {}) {
  const scenarios = await collectValidatedScenarioCatalog();
  const componentIndex = JSON.parse(
    await readFile(componentScenarioIndexPath, "utf8"),
  );
  const wroteUiDoc = await writeGeneratedText(
    uiAgentDocPath,
    await renderUiAgentIterationDoc({ scenarios, componentIndex }),
    { check },
  );
  const wroteReferenceDoc = await writeGeneratedText(
    referenceGamesDocPath,
    await renderReferenceGamesDoc({ scenarios }),
    { check },
  );
  return { wroteUiDoc, wroteReferenceDoc };
}

async function main() {
  const check = process.argv.includes("--check");
  await generateUiAgentDocs({ check });
  console.log(
    `${check ? "checked" : "generated"} ${repoRelative(
      uiAgentDocPath,
    )} and ${repoRelative(referenceGamesDocPath)}`,
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
